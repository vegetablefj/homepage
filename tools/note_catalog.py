"""Generate native PreTeXt configuration and note lists from one catalog.

The catalog only contains material suitable for the public source repository.
An unlisted note is still public. Private drafts belong outside this repository.
"""
from copy import deepcopy
from datetime import date
import argparse
import json
from pathlib import Path, PurePosixPath
import re

try:
    from .runtime import configure
except ImportError:
    from runtime import configure
configure()
from lxml import etree


ROOT = Path(__file__).resolve().parent.parent
MARKER = 'Generated by tools/note_catalog.py; edit config/notes.json instead.'
SLUG = re.compile(r'[a-z][a-z0-9]*(?:-[a-z0-9]+)*\Z')
XML_ID = re.compile(r'[A-Za-z_][A-Za-z0-9_.-]*\Z')
RESERVED = {'con', 'prn', 'aux', 'nul'} | {
    name + str(number) for name in ('com', 'lpt') for number in range(1, 10)}
PUBLICATION_ATTRIBUTES = {
    'common/chunking': {'level'},
    'common/tableofcontents': {'level'},
    'numbering/divisions': {'level', 'chapter-start', 'part-structure'},
    'numbering/blocks': {'level'},
    'numbering/equations': {'level'},
    'numbering/footnotes': {'level'},
    'html/css': {'theme', 'palette', 'provide-dark-mode', 'primary-color', 'secondary-color'},
    'html/platform': {'host', 'portable'},
    'html/resources': {'host'},
    'html/search': {'variant'},
    'html/annotation': {'platform'},
    'html/cross-references': {'knowled'},
    'html/knowl': {'theorem', 'proof', 'definition', 'example', 'remark', 'figure', 'table', 'list'},
    'html/navigation': {'logic', 'upbutton'},
    'html/tableofcontents': {'focused', 'preexpanded-levels'},
}
NOTE_FIELDS = {'slug', 'target', 'source', 'output', 'visibility', 'list_order',
               'selected', 'selection_order', 'description_ptx', 'metadata', 'publication'}
METADATA_FIELDS = {'footnotes', 'status', 'last_updated'}


def _relative(value, label):
    if not isinstance(value, str) or not value or '\\' in value or ':' in value:
        raise ValueError(f'{label} must be a relative path using forward slashes')
    path = PurePosixPath(value)
    if path.is_absolute() or any(part in ('', '.', '..') for part in value.split('/')):
        raise ValueError(f'Unsafe {label}: {value}')
    return path


def _metadata(value, label):
    if not isinstance(value, dict) or set(value) - METADATA_FIELDS:
        raise ValueError(f'Invalid metadata for {label}')
    if value.get('footnotes', 'margin') not in ('margin', 'inline'):
        raise ValueError(f'Footnotes must be margin or inline for {label}')
    for key, item in value.items():
        if item is not None and not isinstance(item, str):
            raise ValueError(f'{key} must be text for {label}')
    if value.get('last_updated'):
        date.fromisoformat(value['last_updated'])
    return deepcopy(value)


def _description(value, label):
    if not isinstance(value, str):
        raise ValueError(f'description_ptx must be text for {label}')
    try:
        fragment = etree.fromstring(('<fragment>' + value + '</fragment>').encode('utf-8'),
                                    etree.XMLParser(no_network=True, resolve_entities=False))
    except etree.XMLSyntaxError as error:
        raise ValueError(f'Invalid description_ptx for {label}: {error}') from error
    if (fragment.text or '').strip() or any(
            node.tag != 'p' or (node.tail or '').strip() for node in fragment):
        raise ValueError(f'description_ptx must contain p elements for {label}')
    return list(fragment)


def load_catalog(root=ROOT):
    """Read and validate the catalog; derive public titles and existing URLs."""
    root = Path(root).resolve()
    data = json.loads((root / 'config/notes.json').read_text(encoding='utf-8'))
    if set(data) - {'version', 'defaults', 'notes'} or data.get('version') != 1:
        raise ValueError('Unsupported note catalog version or fields')
    defaults = _metadata(data.get('defaults', {}), 'defaults')
    if not isinstance(data.get('notes'), list):
        raise ValueError('notes must be an ordered array')
    result = {'version': 1, 'defaults': defaults, 'notes': []}
    seen = {key: set() for key in ('slug', 'target', 'source', 'output', 'document_id')}
    for raw in data['notes']:
        if not isinstance(raw, dict) or set(raw) - NOTE_FIELDS:
            raise ValueError('Unknown note fields')
        note = deepcopy(raw)
        slug = note.get('slug')
        if not isinstance(slug, str) or not SLUG.fullmatch(slug) or slug in RESERVED:
            raise ValueError(f'Unsafe note slug: {slug}')
        target = note.setdefault('target', 'note-' + slug)
        if not isinstance(target, str) or not target.startswith('note-') or not SLUG.fullmatch(target):
            raise ValueError(f'Unsafe target for {slug}')
        visibility = note.setdefault('visibility', 'unlisted')
        if visibility not in ('public', 'unlisted', 'private'):
            raise ValueError(f'Invalid visibility for {slug}')
        selected = note.setdefault('selected', False)
        if not isinstance(selected, bool) or (selected and visibility != 'public'):
            raise ValueError(f'Only a public note can be selected: {slug}')
        for order in ('list_order', 'selection_order'):
            if order in note and (type(note[order]) is not int or note[order] < 0):
                raise ValueError(f'{order} must be a nonnegative integer for {slug}')
        source = note.get('source')
        if visibility == 'private':
            # Exclusion from a build does not protect files committed to Git.
            if not isinstance(source, str) or not Path(source).is_absolute():
                raise ValueError(f'Private drafts must be outside the public repository: {slug}')
            private_path = Path(source).expanduser().resolve()
            if private_path.is_relative_to(root):
                raise ValueError(f'Private drafts must be outside the public repository: {slug}')
            note['source'] = str(private_path)
        else:
            relative = _relative(source, f'source for {slug}')
            if relative.parts[:2] != ('source', 'notes') or relative.suffix != '.ptx':
                raise ValueError(f'Note source must be a PTX file under source/notes: {slug}')
            source_path = (root / relative).resolve()
            if not source_path.is_relative_to((root / 'source/notes').resolve()):
                raise ValueError(f'Note source escapes source/notes: {slug}')
            parser = etree.XMLParser(no_network=True, resolve_entities=False)
            source_xml = etree.parse(str(source_path), parser)
            documents = source_xml.xpath('/pretext/book | /pretext/article')
            if len(documents) != 1:
                raise ValueError(f'Expected one book or article in {source}')
            document = documents[0]
            document_id = document.get('{http://www.w3.org/XML/1998/namespace}id')
            title = document.find('title')
            if not document_id or not XML_ID.fullmatch(document_id) or title is None:
                raise ValueError(f'Note needs a safe document ID and title: {slug}')
            note['document_id'] = document_id
            note['title'] = ''.join(title.itertext()).strip()
        output = note.setdefault('output', 'notes/' + slug)
        relative_output = _relative(output, f'output for {slug}')
        if (len(relative_output.parts) < 2 or relative_output.parts[0] != 'notes'
                or any(not SLUG.fullmatch(part) or part in RESERVED for part in relative_output.parts[1:])):
            raise ValueError(f'Note output must be a safe subdirectory of notes: {slug}')
        note['metadata'] = _metadata(note.get('metadata', {}), slug)
        _description(note.get('description_ptx', ''), slug)
        overrides = note.setdefault('publication', {})
        if not isinstance(overrides, dict):
            raise ValueError(f'Invalid publication overrides for {slug}')
        for path, attributes in overrides.items():
            if (path not in PUBLICATION_ATTRIBUTES or not isinstance(attributes, dict)
                    or set(attributes) - PUBLICATION_ATTRIBUTES[path]
                    or any(value is not None and type(value) not in (str, int) for value in attributes.values())):
                raise ValueError(f'Invalid publication override {path} for {slug}')
        for key in seen:
            if key not in note:
                continue
            if note[key] in seen[key]:
                raise ValueError(f'Duplicate note {key}: {note[key]}')
            seen[key].add(note[key])
        if visibility != 'private':
            note['entry'] = output + '/' + note['document_id'] + '.html'
        result['notes'].append(note)
    return result


def _xml_bytes(element):
    element = deepcopy(element)
    tree = etree.ElementTree(element)
    element.addprevious(etree.Comment(MARKER))
    etree.indent(tree, space='  ')
    return etree.tostring(tree, xml_declaration=True, encoding='UTF-8', pretty_print=True)


def _publication(root, note):
    parser = etree.XMLParser(no_network=True, resolve_entities=False, remove_blank_text=True)
    publication = etree.parse(str(root / 'publication/note-template.ptx'), parser).getroot()
    if publication.tag != 'publication':
        raise ValueError('note-template.ptx must contain publication')
    for path, attributes in note['publication'].items():
        node = publication.find(path)
        if node is None:
            parent_path, tag = path.rsplit('/', 1)
            parent = publication.find(parent_path)
            if parent is None:
                raise ValueError(f'Publication template is missing {parent_path}')
            node = etree.SubElement(parent, tag)
        for key, value in attributes.items():
            if value is None:
                node.attrib.pop(key, None)
            else:
                node.set(key, str(value))
    publication.find('html/index-page').set('ref', note['document_id'])
    return _xml_bytes(publication)


def _listing(root, notes):
    if not notes:
        return _xml_bytes(etree.Element('p'))
    listing = etree.Element('ul')
    for note in notes:
        item = etree.SubElement(listing, 'li')
        paragraph = etree.SubElement(item, 'p')
        url = etree.SubElement(etree.SubElement(paragraph, 'alert'), 'url', href=note['entry'])
        source = etree.parse(str(root / note['source']), etree.XMLParser(no_network=True, resolve_entities=False))
        title = source.xpath('/pretext/book/title | /pretext/article/title')[0]
        url.text = title.text
        for child in title:
            url.append(deepcopy(child))
        for paragraph in _description(note.get('description_ptx', ''), note['slug']):
            item.append(paragraph)
    return _xml_bytes(listing)


def render_catalog(root=ROOT):
    """Return generated relative paths and bytes without changing the checkout."""
    root = Path(root).resolve()
    catalog = load_catalog(root)
    notes = [n for n in catalog['notes'] if n['visibility'] != 'private']
    project = etree.Element('project', attrib={'ptx-version': '2', 'source': 'source',
        'publication': 'publication', 'output-dir': '.build/staging', 'xsl': 'xsl'})
    targets = etree.SubElement(project, 'targets')
    etree.SubElement(targets, 'target', attrib={'name': 'web', 'format': 'html',
        'source': 'main.ptx', 'publication': 'publication.ptx', 'output-dir': '.', 'xsl': 'site-html.xsl'})
    files = {}
    settings = {'defaults': catalog['defaults'], 'notes': {}}
    for note in notes:
        publication = 'generated/' + note['slug'] + '.ptx'
        etree.SubElement(targets, 'target', attrib={'name': note['target'], 'format': 'html',
            'source': PurePosixPath(note['source']).relative_to('source').as_posix(),
            'publication': publication, 'output-dir': note['output'], 'xsl': 'note-html.xsl'})
        files['publication/' + publication] = _publication(root, note)
        settings['notes'][note['target']] = note['metadata']
    files['project.ptx'] = _xml_bytes(project)
    files['publication/generated/note-settings.json'] = (
        json.dumps(settings, indent=2, ensure_ascii=False) + '\n').encode('utf-8')
    listed = [n for n in notes if n['visibility'] == 'public']
    listed.sort(key=lambda n: n.get('list_order', 1000000))
    selected = [n for n in listed if n['selected']]
    selected.sort(key=lambda n: n.get('selection_order', 1000000))
    files['source/generated/notes-list.ptx'] = _listing(root, listed)
    files['source/generated/selected-notes-list.ptx'] = _listing(root, selected)
    return files


def ensure_catalog(root=ROOT, check=False):
    """Synchronize generated native files, or fail if they are stale in check mode."""
    root = Path(root).resolve()
    files = render_catalog(root)
    changed = [name for name, content in files.items()
               if not (root / name).is_file() or (root / name).read_bytes() != content]
    extras = [path for path in (root / 'publication/generated').glob('*.ptx')
              if path.relative_to(root).as_posix() not in files]
    if check and (changed or extras):
        stale = changed + [path.relative_to(root).as_posix() for path in extras]
        raise ValueError('Generated note configuration is stale: ' + ', '.join(stale))
    if not check:
        for name in changed:
            path = root / name
            if not path.resolve().is_relative_to(root):
                raise ValueError('Generated configuration escapes project: ' + name)
            path.parent.mkdir(parents=True, exist_ok=True)
            pending = path.with_name(path.name + '.tmp')
            pending.write_bytes(files[name])
            pending.replace(path)
        for path in extras:
            if not path.resolve().is_relative_to((root / 'publication/generated').resolve()):
                raise ValueError('Generated publication escapes project')
            path.unlink()
    return root / 'project.ptx'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check generated files without writing them.')
    args = parser.parse_args()
    try:
        ensure_catalog(check=args.check)
    except (OSError, ValueError, etree.XMLSyntaxError) as error:
        parser.exit(1, str(error) + '\n')
    print('Note catalog and generated configuration are current.' if args.check
          else 'Generated native PreTeXt configuration and note lists from config/notes.json.')


if __name__ == '__main__':
    main()
